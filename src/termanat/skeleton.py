"""ASCII art of the human skeleton (anterior view) and a per-character bone mask.

The drawing is authored as the *left half* of the picture plus a center column.
The right half is generated by mirroring, which keeps the skeleton symmetric and
guarantees that every bone is highlighted on both sides of the body.

Each row is ``(segments, center_char, center_mask)`` where a segment is
``(column, text, mask)``. ``mask`` is either a single bone key applied to every
non-space character of ``text``, or a string of the same length giving one key
per character (a space means "not part of any bone").

The figure is in anatomical position and seen from the front, so the left half
of the screen is the subject's *right* side.
"""

from __future__ import annotations

HALF_WIDTH = 20
_MIRROR = str.maketrans("/\\()<>[]{}", "\\/)(><][}{")


def _rib(n: int) -> tuple[int, str, str]:
    """A rib row: ``n`` rib characters ending next to the sternum."""
    return (HALF_WIDTH - n - 2, "=" * n + "\\_", "R")


_ARM = 7  # column of the humerus / forearm
_HAND = 6
_LEG = 15  # column of the femur / tibia / fibula

_ROWS: list[tuple[list[tuple[int, str, str]], str, str]] = [
    # skull
    ([(14, '.-""""', "S")], '"', "S"),
    ([(13, "/", "S")], " ", " "),
    ([(13, "|", "S"), (16, ".-.", "S")], " ", " "),
    ([(13, "|", "S"), (16, "'-'", "S")], " ", " "),
    ([(13, "\\", "S")], "^", "S"),
    ([(14, "\\,,,,,", "S")], ",", "S"),
    # mandible
    ([(15, "|''''", "M")], "'", "M"),
    ([(16, "\\___", "M")], "_", "M"),
    # neck & shoulder girdle
    ([], "#", "C"),
    ([(_ARM, ".__", "X"), (_ARM + 3, ".--------'", "L")], "#", "C"),
    # thorax + upper arm
    ([(_ARM, "(__", "H"), _rib(3)], "|", "T"),
    ([(_ARM, "| |", "H"), _rib(5)], "|", "T"),
    ([(_ARM, "| |", "H"), _rib(6)], "|", "T"),
    ([(_ARM, "| |", "H"), _rib(5)], "|", "T"),
    ([(_ARM, "| |", "H"), _rib(4)], "v", "T"),
    ([(_ARM, "| |", "H"), (15, "==\\", "R")], "#", "V"),
    ([(_ARM, "|_|", "H")], "#", "V"),
    # forearm (radius on the thumb / outer side, ulna on the inner side) + pelvis
    ([(_ARM, "/ \\", "D U")], "#", "V"),
    ([(_ARM, "| |", "D U"), (16, "_.-'", "P")], "#", "V"),
    ([(_ARM, "| |", "D U"), (15, "/  .-", "P  YY")], "-", "Y"),
    ([(_ARM, "| |", "D U"), (15, "\\  \\ ", "P  Y ")], "#", "Y"),
    ([(_ARM, "| |", "D U"), (16, "'._\\", "PPPY")], "v", "Y"),
    # hands + thighs
    ([(_ARM, "{=}", "A"), (_LEG, "| |", "F")], " ", " "),
    ([(_HAND, "{###}", "A"), (_LEG, "| |", "F")], " ", " "),
    ([(_HAND, "|||||", "A"), (_LEG, "| |", "F")], " ", " "),
    ([(_HAND, "'''''", "A"), (_LEG, "| |", "F")], " ", " "),
    ([(_LEG, "| |", "F")], " ", " "),
    ([(_LEG, "| |", "F")], " ", " "),
    ([(_LEG, "|_|", "F")], " ", " "),
    # knee
    ([(_LEG, "(_)", "K")], " ", " "),
    # leg (fibula on the outer side, tibia on the inner side)
    ([(_LEG, "| |", "I B")], " ", " "),
    ([(_LEG, "| |", "I B")], " ", " "),
    ([(_LEG, "| |", "I B")], " ", " "),
    ([(_LEG, "| |", "I B")], " ", " "),
    ([(_LEG, "|_|", "IBB")], " ", " "),
    # feet
    ([(_LEG - 1, "/###\\", "O")], " ", " "),
    ([(_LEG - 2, "(_____)", "O")], " ", " "),
]


def _build() -> tuple[list[str], list[str]]:
    art: list[str] = []
    mask: list[str] = []
    for segments, center, center_mask in _ROWS:
        a = [" "] * HALF_WIDTH
        m = [" "] * HALF_WIDTH
        for col, text, mk in segments:
            if len(mk) == 1:
                mk = mk * len(text)
            if len(mk) != len(text) or col + len(text) > HALF_WIDTH:
                raise ValueError(f"bad segment {text!r} at column {col}")
            for i, (ch, key) in enumerate(zip(text, mk)):
                if a[col + i] != " ":
                    raise ValueError(f"overlapping segment {text!r} at column {col}")
                a[col + i] = ch
                m[col + i] = key if ch != " " else " "
        left, left_mask = "".join(a), "".join(m)
        art.append(left + center + left[::-1].translate(_MIRROR))
        mask.append(left_mask + (center_mask if center != " " else " ") + left_mask[::-1])
    return art, mask


ART, MASK = _build()
WIDTH = 2 * HALF_WIDTH + 1
HEIGHT = len(ART)


def bone_at(x: int, y: int) -> str | None:
    """Return the bone key drawn at column ``x``, row ``y`` (or ``None``)."""
    if 0 <= y < HEIGHT and 0 <= x < WIDTH:
        key = MASK[y][x]
        return None if key == " " else key
    return None


def bone_at_or_near(x: int, y: int) -> str | None:
    """Like :func:`bone_at` but tolerant of clicks on the gaps inside a bone."""
    for dx in (0, -1, 1, -2, 2):
        key = bone_at(x + dx, y)
        if key:
            return key
    return None
